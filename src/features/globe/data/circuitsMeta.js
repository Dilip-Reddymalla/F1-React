export function getCircuitMeta(circuitId) {
  if (!circuitId) return null;
  const key = circuitId.toLowerCase().replace(/[\-_]/g, '_');
  return CIRCUITS_META[key] || CIRCUITS_META[getCircuitKey(circuitId)] || null;
}

export function getCircuitTrack(circuitIdOrName) {
  const key = getCircuitKey(circuitIdOrName);
  return CIRCUIT_TRACKS[key] || CIRCUIT_TRACKS.generic;
}

export function getCircuitTimezone(circuitId) {
  return getCircuitMeta(circuitId)?.timezone || 'UTC';
}

export { CIRCUIT_TRACKS, getCircuitKey };
